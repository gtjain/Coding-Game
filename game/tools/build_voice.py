"""Record every spoken line once, as small MP3 files, and write audio/voices.js (text -> file).

Engines:
  kokoro      free, open-source, runs offline (default). Needs kokoro-onnx, soundfile, ffmpeg,
              and the model files kokoro-v1.0.int8.onnx + voices-v1.0.bin (from the
              thewh1teagle/kokoro-onnx GitHub releases) in --models.
  elevenlabs  paid API, needs ELEVENLABS_API_KEY and --voice set to an ElevenLabs voice id.

Clips are named by a hash of engine + voice + text, so re-running only records new or changed lines.

Usage:
  node tools/phrases.mjs > tools/phrases.json
  python tools/build_voice.py --models /path/to/models [--voice af_heart] [--engine kokoro]
"""
import argparse, hashlib, json, os, subprocess, sys, tempfile, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIO = ROOT / "audio"


def clip_name(engine, voice, text):
    return hashlib.sha1(f"{engine}|{voice}|{text}".encode()).hexdigest()[:12] + ".mp3"


def to_mp3(wav_path, mp3_path):
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav_path), "-ac", "1", "-b:a", "48k", str(mp3_path)], check=True)


class Kokoro:
    def __init__(self, models, voice, speed):
        import soundfile  # noqa: F401
        from kokoro_onnx import Kokoro as K
        self.k = K(str(Path(models) / "kokoro-v1.0.int8.onnx"), str(Path(models) / "voices-v1.0.bin"))
        self.voice, self.speed = voice, speed

    def render(self, text, out):
        import soundfile as sf
        lang = "en-gb" if self.voice[0] in "bh" else "en-us"   # h* = Hindi-trained voices: Indian-accented English
        samples, sr = self.k.create(text, voice=self.voice, speed=self.speed, lang=lang)
        with tempfile.NamedTemporaryFile(suffix=".wav") as tmp:
            sf.write(tmp.name, samples, sr)
            to_mp3(tmp.name, out)


class ElevenLabs:
    def __init__(self, voice):
        self.key = os.environ.get("ELEVENLABS_API_KEY")
        if not self.key:
            sys.exit("Set ELEVENLABS_API_KEY to use the elevenlabs engine.")
        self.voice = voice

    def render(self, text, out):
        req = urllib.request.Request(
            f"https://api.elevenlabs.io/v1/text-to-speech/{self.voice}?output_format=mp3_44100_64",
            data=json.dumps({"text": text, "model_id": "eleven_multilingual_v2"}).encode(),
            headers={"xi-api-key": self.key, "Content-Type": "application/json", "Accept": "audio/mpeg"})
        with urllib.request.urlopen(req) as r:
            Path(out).write_bytes(r.read())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", default="kokoro", choices=["kokoro", "elevenlabs"])
    ap.add_argument("--voice", default="hf_alpha")
    ap.add_argument("--speed", type=float, default=0.95)
    ap.add_argument("--models", default=".")
    ap.add_argument("--samples", action="store_true", help="also record the voice samples for the grown-up screen")
    a = ap.parse_args()

    phrases = json.loads((ROOT / "tools" / "phrases.json").read_text())
    eng = Kokoro(a.models, a.voice, a.speed) if a.engine == "kokoro" else ElevenLabs(a.voice)
    AUDIO.mkdir(exist_ok=True)
    manifest, made = {}, 0
    for text in phrases:
        name = clip_name(a.engine, a.voice, text)
        if not (AUDIO / name).exists():
            eng.render(text, AUDIO / name)
            made += 1
        manifest[text] = name
    keep = set(manifest.values())
    for f in AUDIO.glob("*.mp3"):          # drop clips for lines that no longer exist
        if f.name not in keep:
            f.unlink()
    (AUDIO / "voices.js").write_text(
        "/* Generated by tools/build_voice.py. Do not edit. */\nwindow.CH_VOICE = " + json.dumps(manifest, indent=1, ensure_ascii=False) + ";\n")
    print(f"{len(manifest)} lines, {made} newly recorded, voice {a.voice} ({a.engine})")

    if a.samples and a.engine == "kokoro":
        (AUDIO / "samples").mkdir(exist_ok=True)
        for v in ["hf_alpha", "hf_beta", "hm_omega", "hm_psi"]:
            Kokoro(a.models, v, a.speed).render("Hi! I'm your coding buddy. Help the bunny reach the carrot!", AUDIO / "samples" / f"{v}.mp3")
        print("samples recorded")


if __name__ == "__main__":
    main()
